using System.Globalization;
using System.Text;

namespace MyChron2Insta360.Tests;

/// <summary>
/// Builds .vbo text the way the Dragy Lap app writes it: LF line endings, unpadded coordinates in
/// minutes with longitude positive West, the UTC date in the comments, one row per fix. The track
/// drifts north-east at the Erzgebirgsring and its heading crosses north, which is where a careless
/// interpolation would show.
/// </summary>
internal static class SyntheticVbo
{
    public const double Lat0 = 50.839931, Lon0 = 13.445244;
    /// <summary>14:41:51.800 UTC, the start of the real Dragy file.</summary>
    public const long Start = 52_911_800;

    public static string Text(int seconds = 10, double hz = 25, long startMs = Start, string date = "24/10/2026",
                              bool utcStarted = true, bool created = true, string newline = "\n")
    {
        var ci = CultureInfo.InvariantCulture;
        var sb = new StringBuilder();
        void Line(string s = "") => sb.Append(s).Append(newline);

        if (created) { Line($"File created on {date} @ {Hhmm(startMs)}"); Line(); }
        Line("[header]");
        foreach (var h in new[] { "satellites", "time", "latitude", "longitude", "velocity kmh", "heading", "height" }) Line(h);
        Line();
        Line("[channel units]");
        Line();
        Line("[comments]");
        Line("Generated by dragy Lap");
        Line("Model: dragy DRG73");
        if (utcStarted) Line($"UTC Date Started: {date} {Hhmm(startMs)}");
        Line();
        Line("[column names]");
        Line("sats time lat long velocity heading height");
        Line();
        Line("[data]");

        int n = (int)(seconds * hz);
        for (int i = 0; i < n; i++)
        {
            double t = i / hz;
            long ms = (startMs + (long)Math.Round(t * 1000)) % 86_400_000;
            double latMin = (Lat0 + t * 1e-5) * 60;
            double lonMin = -(Lon0 + t * 1e-5) * 60;              // East, so negative in VBO minutes
            double kmh = 40 + 10 * Math.Sin(t / 5);
            double heading = (350 + t * 2) % 360;                   // passes through north after 5 s
            Line($"025 {Time(ms)} +{latMin.ToString("0.000000", ci)} {lonMin.ToString("0.000000", ci)} " +
                 $"{kmh.ToString("000.000", ci)} {heading.ToString("000.00", ci)} +00519.90");
        }
        return sb.ToString();
    }

    /// <summary>A minimal file: the given column names and rows, with a UTC date so it can be read.</summary>
    public static string Minimal(string columns, IEnumerable<string> rows, string velocity = "velocity kmh") =>
        $"[header]\nsatellites\ntime\nlatitude\nlongitude\n{velocity}\nheading\nheight\n\n" +
        "[comments]\nUTC Date Started: 24/10/2026 10:00\n\n" +
        $"[column names]\n{columns}\n\n[data]\n" + string.Join("\n", rows) + "\n";

    /// <summary>One Dragy-style data row at the given time of day.</summary>
    public static string Row(string time, string sats = "025") =>
        $"{sats} {time} +3050.395860 -806.714640 021.816 255.76 +00519.90";

    public const string Columns = "sats time lat long velocity heading height";

    /// <summary>Write a .vbo into a fresh temp folder, which the caller deletes.</summary>
    public static string WriteFile(string text, string name = "dragylap_20261024_164151_Synthetic.vbo")
    {
        string dir = Path.Combine(Path.GetTempPath(), "m2i-tests", Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(dir);
        string path = Path.Combine(dir, name);
        File.WriteAllText(path, text);
        return path;
    }

    public static string Time(long ms) =>
        string.Create(CultureInfo.InvariantCulture,
            $"{ms / 3_600_000:00}{ms / 60_000 % 60:00}{ms / 1000 % 60:00}.{ms % 1000:000}");

    private static string Hhmm(long ms) =>
        string.Create(CultureInfo.InvariantCulture, $"{ms / 3_600_000:00}:{ms / 60_000 % 60:00}");
}
